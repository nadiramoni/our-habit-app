#!/usr/bin/env node
/**
 * update-ads.mjs — ships the owner's REAL Adsterra banner codes to both
 * config sources the APK reads:
 *   1. Firestore app/meta (live source — cfg.ads.adsterra + cfg.at.banner300)
 *   2. src/lib/baked-cfg.ts (offline fallback baked into the build)
 *
 * Codes (owner-provided 2026-10-29):
 *   • 468×60 main banner  → ads.adsterra   (mid + bottom home slots)
 *   • 320×50 small banner → at.banner300   (top home slot)
 *
 * Firestore write path: REST PATCH with nested leaf field masks, so every
 * other config field (firebase, latestVersion, …) stays untouched.
 * The project's current rules allow this write (verified by probe).
 */
import fs from "node:fs";

const API_KEY = "AIzaSyAfnGjQ22LCDaJTDqj2cogaQ8NkLd1FdSY"; // owner's web API key (public by design)
const PROJECT = "our-habit-61587";
const META_URL = `https://firestore.googleapis.com/v1/projects/${PROJECT}/databases/(default)/documents/app/meta`;

const BANNER_468 = `atOptions = {
  'key' : 'e29a2af548bd3c9fa5512bd423e484a5',
  'format' : 'iframe',
  'height' : 60,
  'width' : 468,
  'params' : {}
};
<script src="https://bicea.org/22/e29a2af548bd3c9fa5512bd423e484a5"></script>`;

const BANNER_320 = `atOptions = {
  'key' : 'a19161feecb13d6d32cfa3a7f599f5a2',
  'format' : 'iframe',
  'height' : 50,
  'width' : 320,
  'params' : {}
};
<script src="https://bicea.org/22/a19161feecb13d6d32cfa3a7f599f5a2"></script>`;

const log = (m) => console.log(`[update-ads] ${m}`);

// ---------- 1. Firestore PATCH (nested leaf masks — siblings preserved) ----------
const body = {
  fields: {
    cfg: {
      mapValue: {
        fields: {
          ads: {
            mapValue: {
              fields: {
                adsterra: {
                  mapValue: {
                    fields: { on: { booleanValue: true }, id: { stringValue: BANNER_468 } },
                  },
                },
              },
            },
          },
          at: {
            mapValue: {
              fields: {
                banner300: {
                  mapValue: {
                    fields: { on: { booleanValue: true }, code: { stringValue: BANNER_320 } },
                  },
                },
              },
            },
          },
        },
      },
    },
  },
};

const mask = ["cfg.ads.adsterra", "cfg.at.banner300"].map((p) => `updateMask.fieldPaths=${p}`).join("&");
log("PATCH Firestore app/meta (ads.adsterra = 468×60, at.banner300 = 320×50) …");
const res = await fetch(`${META_URL}?${mask}&key=${API_KEY}`, {
  method: "PATCH",
  headers: { "Content-Type": "application/json" },
  body: JSON.stringify(body),
});
if (!res.ok) {
  console.error(`[update-ads] ✗ Firestore PATCH failed: HTTP ${res.status} — ${await res.text()}`);
  process.exit(1);
}
log("Firestore PATCH ✓");

// ---------- 2. verify what the APK will actually read ----------
const check = await fetch(`${META_URL}?key=${API_KEY}`);
const doc = await check.json();
const cfg = doc.fields?.cfg?.mapValue?.fields ?? {};
const ad = cfg.ads?.mapValue?.fields?.adsterra?.mapValue?.fields ?? {};
const b3 = cfg.at?.mapValue?.fields?.banner300?.mapValue?.fields ?? {};
const adId = ad.id?.stringValue || "";
const b3Code = b3.code?.stringValue || "";
const ok468 = /e29a2af548bd3c9fa5512bd423e484a5/.test(adId) && ad.on?.booleanValue === true;
const ok320 = /a19161feecb13d6d32cfa3a7f599f5a2/.test(b3Code) && b3.on?.booleanValue === true;
log(`verify ads.adsterra → on=${ad.on?.booleanValue}, key=${adId.match(/([a-f0-9]{32})/)?.[1] || "NONE"} ${ok468 ? "✓" : "✗"}`);
log(`verify at.banner300 → on=${b3.on?.booleanValue}, key=${b3Code.match(/([a-f0-9]{32})/)?.[1] || "NONE"} ${ok320 ? "✓" : "✗"}`);
if (!ok468 || !ok320) {
  console.error("[update-ads] ✗ verification failed — Firestore still holds old codes");
  process.exit(1);
}

// ---------- 3. regenerate src/lib/baked-cfg.ts (same slim shape, new codes) ----------
const OUT = "src/lib/baked-cfg.ts";
const src = fs.readFileSync(OUT, "utf8");
const m = src.match(/BAKED_SERVER_CFG: string \| null =\s*\n?\s*(".*");?\s*$/s);
if (!m) {
  console.error("[update-ads] ✗ could not parse baked-cfg.ts");
  process.exit(1);
}
const baked = JSON.parse(JSON.parse(m[1])); // string → JSON string → object
baked.adsEnabled = true;
baked.ads = { ...(baked.ads || {}), adsterra: { on: true, id: BANNER_468 } };
baked.at = { ...(baked.at || {}), banner300: { on: true, code: BANNER_320 } };
baked.at = {
  banner300: { on: true, code: BANNER_320 },
  banner728: baked.at?.banner728 ?? { on: true, code: "" },
  nativeBanner: baked.at?.nativeBanner ?? { on: true, code: "" },
  socialBar: baked.at?.socialBar ?? { on: true, code: "" },
  popunder: baked.at?.popunder ?? { on: false, code: "" },
  smartlink: baked.at?.smartlink ?? { on: true, code: "" },
};
const ts = `// AUTO-GENERATED by scripts/update-ads.mjs — do not edit by hand.
// Baked at ${new Date().toISOString()} — owner's REAL Adsterra codes (468×60 main + 320×50 top).
// Resolution order in cfg.tsx: server /api/config → Firestore app/meta → THIS.
export const BAKED_SERVER_CFG: string | null =
  ${JSON.stringify(JSON.stringify(baked))};
`;
fs.writeFileSync(OUT, ts);
log(`baked-cfg.ts rewritten ✓ (adsterra=468×60 e29a…, banner300=320×50 a191…, firebase=${baked.firebase?.on})`);
log("✅ both ad config sources now carry the owner's live banners");
