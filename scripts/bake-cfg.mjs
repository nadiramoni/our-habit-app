#!/usr/bin/env node
/**
 * bake-cfg.mjs — regenerates src/lib/baked-cfg.ts from the live server config.
 * Source: prisma AppConfig 'cfg' (same data the admin panel saves).
 * Run before releasing a new APK so the baked fallback matches the owner's
 * latest ads/firebase/update config. (CI runs it automatically before build.)
 */
let prisma = null;
try {
  const { PrismaClient } = await import("@prisma/client");
  prisma = new PrismaClient();
} catch {
  // client not generated / not installed — keep the committed baked config
  console.log("[bake-cfg] no prisma client here — keeping the committed baked config ✓");
  process.exit(0);
}
import fs from "node:fs";
const OUT = "src/lib/baked-cfg.ts";

let row = null;
try {
  row = await prisma.appConfig.findUnique({ where: { key: "cfg" } });
} catch {
  // CI: no database in the repo — keep the baked-cfg.ts already committed.
  console.log("[bake-cfg] no DB here (CI) — keeping the committed baked config ✓");
  process.exit(0);
}
if (!row) {
  console.log("[bake-cfg] no cfg row — keeping existing baked config");
  process.exit(0);
}
const v = JSON.parse(row.value);

// Only the fields APK users need — ads + firebase + update config.
const slim = {
  adsEnabled: Boolean(v.adsEnabled),
  ads: {
    adsterra: v.ads?.adsterra ?? { on: false, id: "" },
    banner: { on: false, id: "" },
    native: { on: false, id: "" },
    rewarded: { on: false, id: "" },
    adsense: { on: false, id: "" },
  },
  at: v.at ?? {},
  firebase: v.firebase ?? { on: false, config: "" },
  latestVersion: v.latestVersion ?? "",
  apkUrl: v.apkUrl ?? "",
  changelog: v.changelog ?? "",
  forceUpdate: Boolean(v.forceUpdate),
  // v5.3.0: FCM push config — baked so even the FIRST run offline can push
  fcmServerKey: v.fcmServerKey ?? "",
  pushRelayUrl: v.pushRelayUrl ?? "",
  pushRelaySecret: v.pushRelaySecret ?? "",
};

// NOTE: baked latestVersion/apkUrl snapshot the value at build time; the live
// app/meta doc (checked every 5 min) always wins when reachable.
const ts = `// AUTO-GENERATED by scripts/bake-cfg.mjs — do not edit by hand.
// Baked at ${new Date().toISOString()} from the live server config.
// Resolution order in cfg.tsx: server /api/config → Firestore app/meta → THIS.
export const BAKED_SERVER_CFG: string | null =
  ${JSON.stringify(JSON.stringify(slim))};
`;

fs.writeFileSync(OUT, ts);
console.log(`[bake-cfg] wrote ${OUT} (adsEnabled=${slim.adsEnabled}, adsterra=${slim.ads.adsterra?.on}, fb=${slim.firebase?.on}, latestVersion="${slim.latestVersion}")`);
await prisma.$disconnect();
